-- Run in Snowsight as ACCOUNTADMIN, using Run All. Replace <PUBLIC_KEY> with the public key
-- (the content of the .pub file without the BEGIN and END lines and without line breaks).
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS AIRBYTE_ROLE;
CREATE USER IF NOT EXISTS AIRBYTE_USER
  TYPE = SERVICE
  DEFAULT_ROLE = AIRBYTE_ROLE
  RSA_PUBLIC_KEY = '<PUBLIC_KEY>';
GRANT ROLE AIRBYTE_ROLE TO USER AIRBYTE_USER;

USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS AIRBYTE_WAREHOUSE
  WAREHOUSE_SIZE = XSMALL
  WAREHOUSE_TYPE = STANDARD
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS AIRBYTE_DATABASE;
GRANT USAGE ON WAREHOUSE AIRBYTE_WAREHOUSE TO ROLE AIRBYTE_ROLE;
GRANT OWNERSHIP ON DATABASE AIRBYTE_DATABASE TO ROLE AIRBYTE_ROLE COPY CURRENT GRANTS;

USE ROLE ACCOUNTADMIN;
ALTER USER AIRBYTE_USER SET DEFAULT_WAREHOUSE = AIRBYTE_WAREHOUSE;

-- Checks
SHOW USERS LIKE 'AIRBYTE_USER';
SHOW WAREHOUSES LIKE 'AIRBYTE_WAREHOUSE';
SHOW DATABASES LIKE 'AIRBYTE_DATABASE';

-- Found while testing the Airbyte destination: the PUBLIC schema inside the new database stayed owned by
-- SYSADMIN, so AIRBYTE_ROLE could not use it. Give the schema to AIRBYTE_ROLE as well.
USE ROLE ACCOUNTADMIN;
GRANT OWNERSHIP ON SCHEMA AIRBYTE_DATABASE.PUBLIC TO ROLE AIRBYTE_ROLE COPY CURRENT GRANTS;
