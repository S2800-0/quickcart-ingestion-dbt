-- Run in Snowsight as ACCOUNTADMIN, using Run All. Replace <PUBLIC_KEY> with the public key
-- (the content of rsa_key.pub without the BEGIN and END lines and without line breaks).
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS FIVETRAN_ROLE;
CREATE USER IF NOT EXISTS FIVETRAN_USER
  TYPE = SERVICE
  DEFAULT_ROLE = FIVETRAN_ROLE
  DEFAULT_WAREHOUSE = FIVETRAN_WAREHOUSE;
GRANT ROLE FIVETRAN_ROLE TO USER FIVETRAN_USER;
GRANT ROLE FIVETRAN_ROLE TO ROLE SYSADMIN;

USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS FIVETRAN_WAREHOUSE
  WAREHOUSE_SIZE = XSMALL
  WAREHOUSE_TYPE = STANDARD
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS FIVETRAN_DATABASE;
GRANT USAGE ON WAREHOUSE FIVETRAN_WAREHOUSE TO ROLE FIVETRAN_ROLE;
GRANT CREATE SCHEMA, MONITOR, USAGE ON DATABASE FIVETRAN_DATABASE TO ROLE FIVETRAN_ROLE;

-- Register the public key for the Fivetran service user
USE ROLE SECURITYADMIN;
ALTER USER FIVETRAN_USER SET RSA_PUBLIC_KEY = '<PUBLIC_KEY>';

-- Checks
SHOW USERS LIKE 'FIVETRAN_USER';
SHOW WAREHOUSES LIKE 'FIVETRAN_WAREHOUSE';
SHOW DATABASES LIKE 'FIVETRAN_DATABASE';
